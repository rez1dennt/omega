import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { mkdir } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = require(resolve(process.env.CODEX_NODE_MODULES, 'playwright'));
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.setDefaultTimeout(5000);
try {
  await page.goto('http://127.0.0.1:4173');
  const combo = page.getByRole('combobox');
  assert.equal(await combo.evaluate(element => element.tagName), 'BUTTON', 'TPI must use the custom control, not an OS select');
  await combo.click();
  await page.getByRole('listbox').waitFor({ state: 'visible' });
  assert.equal(await combo.getAttribute('aria-expanded'), 'true');
  await page.getByRole('option', { name: '4/6 TPI', exact: true }).click();
  assert.equal(await page.locator('input[name="tpi"]').inputValue(), '4/6 TPI');
  assert.match(await combo.textContent(), /4\/6 TPI/);
  assert.equal(await combo.getAttribute('aria-expanded'), 'false');
  await combo.focus();
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('End');
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('input[name="tpi"]').inputValue(), 'Нужна помощь с подбором');
  await combo.click();
  await page.keyboard.press('Escape');
  assert.equal(await combo.getAttribute('aria-expanded'), 'false');
  assert.equal(await combo.evaluate(element => element === document.activeElement), true);
  await combo.click();
  await page.locator('#order-title').click();
  assert.equal(await combo.getAttribute('aria-expanded'), 'false');
  await page.setViewportSize({ width: 320, height: 720 });
  await combo.click();
  const box = await page.getByRole('listbox').boundingBox();
  assert.ok(box.x >= 0 && box.x + box.width <= 320, 'Custom popup must stay inside mobile viewport');
  await mkdir('qa', { recursive: true });
  await page.screenshot({ path: 'qa/custom-dropdown-mobile.png' });
  console.log('PASS: custom TPI dropdown, pointer and keyboard selection, Escape, outside click, mobile geometry.');
} finally { await browser.close(); }
