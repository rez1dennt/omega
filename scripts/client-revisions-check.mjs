async function checkDelayedPitchModule() {
 const delayed=await browser.newPage({viewport:{width:360,height:780},reducedMotion:'reduce'});
 const errors=[];let api=0;let release;
 const gate=new Promise(resolve=>{release=resolve;});
 delayed.on('pageerror',error=>errors.push(error.message));
 await delayed.route('**/*',async route=>{
  const request=route.request();const url=new URL(request.url());
  if(!['GET','HEAD'].includes(request.method())||url.pathname.includes('/api/')){api++;return route.abort();}
  if(url.origin!==new URL(baseURL).origin)return route.fulfill({status:200,contentType:'text/html',body:''});
  if(url.pathname.endsWith('/scripts/pitch-guide.js'))await gate;
  return route.continue();
 });
 try {
  await delayed.goto(baseURL,{waitUntil:'commit'});
  await delayed.waitForFunction(()=>document.querySelectorAll('.selection-placeholder').length===3);
  if(await delayed.locator('#cookie-banner').isVisible())await delayed.locator('#cookie-banner [data-cookie-save]').click();
  await delayed.locator('.hero [data-dialog="selection-dialog"]').click();
  assert.equal(await delayed.locator('#selection-dialog .pitch-card').count(),1,'early open moves guide before delayed module runs');
  release();await delayed.waitForLoadState('networkidle');
  assert.deepEqual(errors,[],'delayed pitch module initializes after guide moves into selection');
  assert.equal(await delayed.locator('#selection-dialog .pitch-tabs').evaluate(el=>el.hidden),false);
  await delayed.locator('.selection-guide>summary').click();
  await delayed.locator('#pitch-rod-diameter').fill('60');await delayed.locator('#pitch-panel-rod .pitch-find').click();
  assert.deepEqual(await delayed.locator('#pitch-panel-rod .pitch-choice strong').allTextContents(),['5/8','5/6','4/6']);
  await delayed.locator('#pitch-panel-rod .pitch-choice').filter({hasText:'5/8'}).click();
  assert.equal(await delayed.locator('#order-form [name="tpi"]').inputValue(),'5/8 TPI');
  await delayed.keyboard.press('Escape');
  await delayed.waitForFunction(()=>!document.documentElement.classList.contains('scroll-locked'));
  assert.equal(await delayed.locator('#pitch-guide .pitch-card').count(),1,'initialized guide restores after early open');
  await delayed.locator('#pitch-tab-pipe').click();
  await delayed.locator('#pitch-pipe-diameter').fill('40');await delayed.locator('#pitch-pipe-wall').fill('3');
  await delayed.locator('#pitch-panel-pipe .pitch-find').click();
  assert.equal(await delayed.locator('#pitch-panel-pipe .pitch-choice strong').textContent(),'8/12','restored guide keeps pipe interaction');
  assert.deepEqual(errors,[]);assert.equal(api,0,'delayed-load regression never sends requests');
  console.log('PASS: delayed pitch module initializes inside an already-open selection, rod/TPI transfer and restored pipe table work. No requests.');
 } finally {release();await delayed.close();}
}
