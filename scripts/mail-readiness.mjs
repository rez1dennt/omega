import assert from 'node:assert/strict';
import { readFile, access } from 'node:fs/promises';
const html = await readFile('dist/index.html', 'utf8');
const js = await readFile('dist/scripts/site.js', 'utf8');
const client = await readFile('dist/scripts/request-client.js', 'utf8');
assert.doesNotMatch(html, /демонстрац|демовер/i, 'production page must not contain demonstration labels');
assert.match(client, /await sendRequest\(payload, form.dataset.endpoint\)/, 'validated forms must call the actual shared request client');
assert.match(js, /attachRequestWorkflow\(orderForm/, 'inline form has its own direct-submit handler');
assert.match(js, /attachRequestWorkflow\(requestForm/, 'modal form retains its direct-submit handler');
await access('php/public_html/api/request.php');
await access('php/private/mail.example.php');
await access('php/private/request-handler.php');
const config = await readFile('php/private/mail.example.php', 'utf8');
assert.match(config, /smtp\.mail\.ru/);
assert.match(config, /465/);
assert.match(config, /enabled.*false/);
const api = await readFile('php/private/request-handler.php', 'utf8');
assert.match(api, /omegakomplekt@mail\.ru/);
assert.match(api, /ENCRYPTION_SMTPS/);
assert.match(api, /csrf/);
for (const route of ['privacy', 'consent']) assert.doesNotMatch(await readFile(`dist/${route}/index.html`, 'utf8'), /демонстрац|демовер/i);
console.log('PASS: production copy and PHP/SMTP configuration. No form submissions or SMTP connections performed.');
